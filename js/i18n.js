  const LS = "bianchi_lang";
  function detect() {
    try { const s = localStorage.getItem(LS); if (s && LANGS[s]) return s; } catch {}
    const nav = (navigator.language || "fr").slice(0, 2).toLowerCase();
    return LANGS[nav] ? nav : "fr";
  }
  let lang = detect();

  const I18N = {
    LANGS,
    get lang() { return lang; },
    set(l) {
      if (!LANGS[l]) return;
      lang = l;
      try { localStorage.setItem(LS, l); } catch {}
      I18N.applyDocument();
      window.dispatchEvent(new CustomEvent("bianchi:lang", { detail: l }));
    },
    applyDocument() {
      document.documentElement.lang = lang;
      document.documentElement.dir = LANGS[lang].dir;
    },
    // Texte d'interface
    t(key, vars) {
      let s = (S[lang] && S[lang][key]) ?? S.fr[key] ?? key;
      if (vars) for (const k in vars) s = s.split("{" + k + "}").join(vars[k]);
      return s;
    },
    // Champ traduit d'un contenu de la base : obj.traductions[lang][field] sinon obj[field] (français)
    c(obj, field) {
      if (!obj) return "";
      const tr = obj.traductions && obj.traductions[lang];
      const v = tr && tr[field];
      return (v && String(v).trim()) ? v : (obj[field] ?? "");
    },
    locale() { return LANGS[lang].locale; },
    devise() { return LANGS[lang].devise; },
    money(n) { return Number(n || 0).toLocaleString(LANGS[lang].locale, { maximumFractionDigits: 2 }) + " " + LANGS[lang].devise; },
    date(d, opts) { return d.toLocaleDateString(LANGS[lang].locale, opts || { weekday: "long", day: "numeric", month: "long" }); },
  };
  window.I18N = I18N;
  I18N.applyDocument();
